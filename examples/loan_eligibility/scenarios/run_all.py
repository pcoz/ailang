"""Run every scenario in this folder through AIEX and capture decisions.

Loads each ``scenario_*.ailang`` file, executes it via the AIEX engine,
extracts the structured decision plus key audit fields, and writes a
markdown report plus a JSON dump to ``../runs/<run-id>/`` so the README
can link to a reproducible record of what each scenario produced.

Each invocation gets its own run directory (default run id: UTC
timestamp, override with ``--run-id``), so two runs can be kept side by
side and compared with ``compare_runs.py``.

Live LLM calls are made.  Two ways to provide your API key:
  1. Export ``ANTHROPIC_API_KEY`` in your shell before running.
  2. Set ``AIEX_ROOT`` to point at your AIEX checkout (which contains a
     ``.env`` file with the key) -- this script will load it.

Budget ~$0.045 per scenario, ~$0.22 total for the five-scenario run.
"""

from __future__ import annotations

import argparse
import datetime
import json
import os
import sys
from pathlib import Path

# Boot the AIEX environment.  Two ways this script finds AIEX:
#   1. ANTHROPIC_API_KEY already in the environment + `aiex` importable
#      via pip-installed package -- nothing to do.
#   2. AIEX_ROOT environment variable points at a sibling AIEX checkout
#      with a .env file -- we load the key from there and prepend its
#      src/ to sys.path.
# This keeps the runner portable across users without hardcoding paths.
if "ANTHROPIC_API_KEY" not in os.environ:
    aiex_root_env = os.environ.get("AIEX_ROOT")
    if aiex_root_env:
        aiex_root = Path(aiex_root_env)
        env_file = aiex_root / ".env"
        if env_file.exists():
            for line in env_file.read_text().splitlines():
                if "=" in line and not line.startswith("#"):
                    k, v = line.split("=", 1)
                    os.environ.setdefault(k.strip(), v.strip())
        src_dir = aiex_root / "src"
        if src_dir.exists():
            sys.path.insert(0, str(src_dir))
    else:
        sys.stderr.write(
            "ANTHROPIC_API_KEY not set and AIEX_ROOT not set.\n"
            "Either export ANTHROPIC_API_KEY in your shell, or set\n"
            "AIEX_ROOT to point at your AIEX checkout (which has a .env).\n"
        )
        sys.exit(1)

from aiex.parser.lexer import Lexer  # noqa: E402  (imports after env setup)
from aiex.parser.parser import Parser  # noqa: E402
from aiex.runtime.engine import AiexEngine  # noqa: E402

HERE = Path(__file__).parent
RUNS_DIR = HERE.parent / "runs"
RUNS_DIR.mkdir(exist_ok=True)

# Scenarios to execute, in the order they should appear in the report.
# Names map to the files generated by ``generate_scenarios.py`` and to
# the human-readable headers used in the markdown report.
SCENARIOS: list[tuple[str, str]] = [
    ("scenario_01_clear_approve", "Scenario 1 -- Clear APPROVE"),
    ("scenario_02_clear_decline", "Scenario 2 -- Clear DECLINE"),
    ("scenario_03_marginal_conditional", "Scenario 3 -- Marginal: conditional approval"),
    ("scenario_04_marginal_decline", "Scenario 4 -- Marginal: decline despite OK score"),
    ("scenario_05_judgment_call", "Scenario 5 -- Edge case: judgment call"),
]


def _find_response(state, fragment: str):
    """Locate a transaction result by name fragment.

    AIEX assigns transaction IDs like ``tx-2-hard_eligibility``.  We
    look up by the fragment (e.g. ``hard_eligibility``) so the report
    code is decoupled from the exact ID format the compiler generates.
    """
    for tx_id, res in state.results.items():
        if fragment in tx_id:
            return res.response
    return None


def run_scenario(scenario_name: str) -> dict:
    """Execute one scenario and return the captured outputs."""
    src_path = HERE / f"{scenario_name}.ailang"
    src = src_path.read_text(encoding="utf-8")
    tokens = Lexer(src).tokenize()
    program = Parser(tokens).parse()

    # verbose=False keeps the run_all output focused on results rather
    # than per-transaction status -- the per-transaction trail is in the
    # AIEX engine's execution log if needed for deeper auditing.
    engine = AiexEngine(verbose=False)
    state = engine.run(program, source_file=scenario_name)

    return {
        "scenario": scenario_name,
        "applicant": state.variables.get("applicant"),
        "affordability_metrics": state.variables.get("affordability_metrics"),
        "hard_eligibility": _find_response(state, "hard_eligibility"),
        "soft_factors": _find_response(state, "soft_factors"),
        "final_decision": _find_response(state, "final_decision"),
        "letter_excerpt": state.variables.get("letter_excerpt"),
        "transactions_committed": sum(
            1 for r in state.results.values() if r.status.value == "COMMITTED"
        ),
        "transactions_rolled_back": sum(
            1 for r in state.results.values() if r.status.value == "ROLLED_BACK"
        ),
    }


def render_markdown(results: list[tuple[str, dict]]) -> str:
    """Build the markdown report from accumulated scenario results."""
    out = []
    out.append("# Loan Eligibility -- Live Execution Report")
    out.append("")
    out.append(f"_Generated: {datetime.datetime.utcnow().isoformat(timespec='seconds')}Z_")
    out.append("")
    out.append(
        "Each scenario runs the same `loan_eligibility.ailang` program "
        "through AIEX with a different applicant.  The reasoning operations "
        "(`DEDUCE`, `WEIGH`, `SYNTHESIZE`) make real LLM calls; the "
        "`EXECUTE_CODE` blocks compute deterministically.  Outputs below "
        "are captured verbatim from the run."
    )
    out.append("")

    for header, result in results:
        out.append(f"## {header}")
        out.append("")
        a = result["applicant"] or {}
        m = result["affordability_metrics"] or {}
        out.append(f"**Applicant:** {a.get('name', '?')}, credit {a.get('credit_score')}, "
                   f"income ${a.get('annual_income_usd', 0):,}/yr, "
                   f"requesting ${a.get('requested_loan_amount_usd', 0):,} "
                   f"over {a.get('requested_term_months')}mo")
        out.append("")
        out.append(f"**Computed metrics (deterministic):** "
                   f"monthly payment ${m.get('monthly_payment_usd')}, "
                   f"DTI {m.get('dti_pct')}%, "
                   f"residual income ${m.get('residual_income_usd')}")
        out.append("")
        he = result["hard_eligibility"] or {}
        out.append(f"**Hard eligibility outcome:** `{he.get('hard_outcome')}`")
        if he.get("failed_checks"):
            out.append(f"  - Failed checks: {', '.join(he['failed_checks'])}")
        out.append("")
        sf = result["soft_factors"] or {}
        out.append(f"**Soft factor direction:** `{sf.get('soft_factor_direction')}`")
        out.append("")
        fd = result["final_decision"] or {}
        out.append(f"**Final decision: `{fd.get('decision')}`** "
                   f"(confidence: {fd.get('confidence')})")
        out.append("")
        if fd.get("primary_rationale"):
            out.append(f"_Rationale:_ {fd['primary_rationale']}")
            out.append("")
        if fd.get("conditions_if_any"):
            out.append("_Conditions:_")
            for c in fd["conditions_if_any"]:
                out.append(f"  - {c}")
            out.append("")
        out.append(f"**Customer letter excerpt:**")
        out.append("")
        out.append(f"> {result['letter_excerpt']}")
        out.append("")
        out.append(f"_Transactions: {result['transactions_committed']} committed, "
                   f"{result['transactions_rolled_back']} rolled back._")
        out.append("")
        out.append("---")
        out.append("")

    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description="Run all loan-eligibility scenarios.")
    ap.add_argument(
        "--run-id",
        default=datetime.datetime.utcnow().strftime("%Y%m%dT%H%M%SZ"),
        help="Name of the output directory under runs/ (default: UTC timestamp).",
    )
    args = ap.parse_args()
    run_dir = RUNS_DIR / args.run_id
    if run_dir.exists():
        sys.exit(f"{run_dir} already exists; pick another --run-id.")
    run_dir.mkdir(parents=True)

    results: list[tuple[str, dict]] = []
    for scenario_name, header in SCENARIOS:
        print(f"Running {scenario_name}...")
        result = run_scenario(scenario_name)
        results.append((header, result))
        decision = (result["final_decision"] or {}).get("decision", "?")
        print(f"  -> {decision}")

    # Save the human-readable report and a machine-readable JSON dump
    # in parallel.  The JSON is useful for diffing future runs against
    # this baseline to detect drift.
    md = render_markdown(results)
    md_path = run_dir / "run_report.md"
    md_path.write_text(md, encoding="utf-8")
    print(f"\nWrote {md_path}")

    json_path = run_dir / "run_report.json"
    json_path.write_text(
        json.dumps([r for _, r in results], indent=2, default=str),
        encoding="utf-8",
    )
    print(f"Wrote {json_path}")


if __name__ == "__main__":
    main()
